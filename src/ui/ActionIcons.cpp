std::string iconFor(const std::string& id)
{
    if (const Action* a = find(id); a && !a->icon.empty())
        return a->icon;
    if (auto it = defaultIcons().find(id); it != defaultIcons().end())
        return std::string(it->second);
    for (const panels::Panel* p : panels::registry().allInOrder())
        if (!p->icon.empty() && (p->toggleAction.empty() ? "window." + p->id : p->toggleAction) == id)
            return p->icon;
    for (const iconBars::Item* item : iconBars::registry().allInOrder())
        if (item->action == id && !item->icon.empty())
            return item->icon;
    return {};
}
